import re
p = 'publish/build_findings.py'
s = open(p).read()


def block(i):
    a = s.index(f"add(id='{i}'")
    b = s.find('\nadd(', a + 5)
    return a, (b if b > 0 else len(s))


def setf(i, k, v):
    global s
    assert "'" not in v, (i, k)
    a, b = block(i); blk = s[a:b]
    pat = re.compile(k + r"=(?:'[^']*'|[A-Za-z_][A-Za-z_0-9]*(?: *\+ *[A-Za-z_0-9]+)*)")
    assert len(pat.findall(blk)) == 1, (i, k, pat.findall(blk))
    blk = pat.sub(lambda _: f"{k}='{v}'", blk, count=1)
    s = s[:a] + blk + s[b:]


def rep(i, old, new):
    global s
    a, b = block(i); blk = s[a:b]
    assert blk.count(old) == 1, (i, old)
    s = s[:a] + blk.replace(old, new) + s[b:]


