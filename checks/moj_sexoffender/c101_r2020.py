import math
def chi2(a,b,c,d,yates=False):
    n=a+b+c+d; num=abs(a*d-b*c)
    if yates: num=max(0,num-n/2)
    return n*num**2/((a+b)*(c+d)*(a+c)*(b+d))
def phi(a,b,c,d): return (a*d-b*c)/math.sqrt((a+b)*(c+d)*(a+c)*(b+d))
