def norm(s): return re.sub(r'[\s　]+', '', html.unescape(s)).replace('，', '、').replace('％', '%')
def text(p):
    if p.endswith('.pdf'): return subprocess.run(['pdftotext', p, '-'], capture_output=True, text=True).stdout
    b = open(p, 'rb').read()
    for enc in ('utf-8', 'cp932', 'euc-jp'):
        try: s = b.decode(enc); break
        except UnicodeDecodeError: continue
    else: s = b.decode('utf-8', 'ignore')
    s = re.sub(r'<(script|style)[^>]*>.*?</\1>', ' ', s, flags=re.S)
    return re.sub(r'<[^>]+>', ' ', s)
res = {}
for q, s in Q.items():
    cand = [os.path.join(RAW, f) for f in os.listdir(RAW) if f.startswith(q)] if os.path.isdir(RAW) else []
    found = None
    for p in cand:
        if norm(s) in norm(text(p)): found = os.path.basename(p)
    res[q] = found
    print(q, '写しで確認' if found else ('写しあり・見つからず' if cand else '写しなし'), len(s), s)
json.dump(res, open('results/citations/QUOTE_CHECK.json', 'w'), ensure_ascii=False, indent=1)
